"""Applies ONE article-production-run result (see sales_ai_employee's
services.article_production_service) to this repo: fills in the
article's PENDING content_id/product_id placeholders and refreshes
functions/_data/redirect-map.js from a full redirect-map-export, so a
new article never needs hand-editing after its production-DB side is
done. Companion to the standard-process work started for article 25
(odor-care) -- see that article's redirect-map.js entry for the shape
this replaces hand-editing of.

Usage:
    python3 scripts/apply_article_production_result.py \\
        --article-slug odor-care \\
        --production-result /path/to/article-production-run-output.json \\
        --redirect-map-export /path/to/redirect-map-export-output.json

Inputs:
  --production-result: the JSON object `article-production-run` prints
    (content_id, product_ids: {item_code: product_id}, status, ...).
    Only used here for its `product_ids` (in item_code order, i.e. the
    same order the article's PENDING product blocks must appear in) and
    `status` (refuses to touch PENDING unless status == "published").
  --redirect-map-export: the JSON `redirect-map-export` writes (the
    FULL {content_id: {product_id: affiliate_url}} mapping for every
    published content) -- this script never tries to merge just one
    content's entries into the existing file itself; it always writes
    the complete, freshly-exported mapping, exactly as the documented
    manual process in functions/README.md already does.

What it does, in order:
  1. Replaces every occurrence of
     `content_id=PENDING&amp;product_id=PENDING` in
     articles/<slug>/index.html, grouped three at a time (image,
     product_name, cta -- this repo's established per-product pattern,
     see e.g. articles/odor-care/index.html before this script's first
     use) in file order, with the Nth group filled from the Nth entry
     of `product_ids` (dict iteration order == item_codes order, both
     insertion-ordered).
  2. Regenerates functions/_data/redirect-map.js as an ES module default
     export of the full --redirect-map-export JSON, sorted-key, with the
     same fixed header comment the file has always had.
  3. Refuses (raises, before writing anything) if the article still has
     a different number of PENDING pairs than `product_ids` entries, or
     if status != "published" -- never a partial/guessed substitution.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PENDING_PAIR = "content_id=PENDING&amp;product_id=PENDING"


class ApplyError(ValueError):
    """The inputs don't match what this repo's article template expects;
    refused before any file was written."""


def _redirect_map_js(mapping: dict) -> str:
    body = json.dumps(mapping, ensure_ascii=False, indent=2, sort_keys=True)
    header = (
        "// Verified redirect mapping (STEP 7D/7F) -- generated by\n"
        "// `python -m sales_ai.cli redirect-map-export`, never hand-edited.\n"
        "// Regenerate and replace this whole file when published content\n"
        "// changes; do not add/remove entries by hand.\n"
        "export default "
    )
    return header + body + ";\n"


def apply_pending_replacement(article_html: str, content_id: int, product_ids: list[int]) -> str:
    """Replace every PENDING pair, three at a time (image/product_name/cta
    per product, in that fixed order), with (content_id, product_ids[i]).
    Raises ApplyError if the count doesn't divide evenly by 3 or doesn't
    match len(product_ids) * 3 -- never substitutes a partial/guessed set.
    """
    pending_count = article_html.count(PENDING_PAIR)
    expected = len(product_ids) * 3
    if pending_count != expected:
        raise ApplyError(
            f"expected {expected} PENDING occurrences (3 per product x "
            f"{len(product_ids)} products), found {pending_count}"
        )

    result = []
    remaining = article_html
    product_index = 0
    occurrence_in_product = 0
    while PENDING_PAIR in remaining:
        head, _, remaining = remaining.partition(PENDING_PAIR)
        result.append(head)
        product_id = product_ids[product_index]
        result.append(f"content_id={content_id}&amp;product_id={product_id}")
        occurrence_in_product += 1
        if occurrence_in_product == 3:
            occurrence_in_product = 0
            product_index += 1
    result.append(remaining)
    return "".join(result)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--article-slug", required=True)
    parser.add_argument("--production-result", required=True, type=Path)
    parser.add_argument("--redirect-map-export", required=True, type=Path)
    args = parser.parse_args(argv)

    result = json.loads(args.production_result.read_text(encoding="utf-8"))
    if result.get("status") != "published":
        raise ApplyError(
            f"production result status is {result.get('status')!r}, not 'published' "
            "-- refusing to replace PENDING for an article that isn't live yet"
        )
    content_id = result["content_id"]
    product_ids = list(result["product_ids"].values())
    if not product_ids:
        raise ApplyError("production result has no product_ids")

    article_path = REPO_ROOT / "articles" / args.article_slug / "index.html"
    article_html = article_path.read_text(encoding="utf-8")
    updated_html = apply_pending_replacement(article_html, content_id, product_ids)
    article_path.write_text(updated_html, encoding="utf-8")

    redirect_mapping = json.loads(args.redirect_map_export.read_text(encoding="utf-8"))
    redirect_map_path = REPO_ROOT / "functions" / "_data" / "redirect-map.js"
    redirect_map_path.write_text(_redirect_map_js(redirect_mapping), encoding="utf-8")

    remaining_pending = updated_html.count("PENDING")
    print(
        f"applied: article={args.article_slug} content_id={content_id} "
        f"products={product_ids} remaining_PENDING_markers={remaining_pending} "
        f"redirect_map_contents={len(redirect_mapping)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
